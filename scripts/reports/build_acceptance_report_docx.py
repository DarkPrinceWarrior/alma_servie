ACCENT = RGBColor(0x1F, 0x3A, 0x5F)


def _col(df, *needles):
    for c in df.columns:
        cl = str(c).lower().replace("ё", "е")
        if all(n in cl for n in needles):
            return c
    return None


def _plot_well(src_dir: str, title: str, out_png: Path) -> Path | None:
    src = Path(src_dir) / "source.parquet"
    starts = Path(src_dir) / "predicted_starts.parquet"
    if not src.exists():
        print(f"[график пропущен] нет {src}")
        return None
    df = pd.read_parquet(src)
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    df = df.sort_values("timestamp")
    p = _col(df, "давление", "прием")
    f = _col(df, "выходная", "частота")
    onset = None
    if starts.exists():
        st = pd.read_parquet(starts)
        if len(st) and "detected_time" in st.columns:
            onset = pd.to_datetime(st["detected_time"]).min()

    fig, axes = plt.subplots(2, 1, figsize=(9.2, 5.0), sharex=True, gridspec_kw={"height_ratios": [2, 1]})
    ax0, ax1 = axes
    ax0.plot(df["timestamp"], df[p], color="#1d4ed8", linewidth=1.1, label="Давление на приёме, кгс/см²")
    ax0.set_ylabel("Давление, кгс/см²")
    ax0.grid(True, alpha=0.25)
    ax0.legend(loc="upper left", fontsize=8)
    if f is not None:
        ax1.plot(df["timestamp"], df[f], color="#7c3aed", linewidth=1.0, label="Выходная частота, Гц")
        ax1.set_ylabel("Частота, Гц")
        ax1.grid(True, alpha=0.25)
        ax1.legend(loc="upper left", fontsize=8)
    if onset is not None:
        for ax in axes:
            ax.axvline(onset, color="#b91c1c", linestyle="--", linewidth=1.4)
        ax0.text(onset, ax0.get_ylim()[1], " момент начала аномалии",
                 color="#b91c1c", fontsize=8, va="top", ha="left")
    ax1.xaxis.set_major_formatter(mdates.DateFormatter("%d.%m"))
    fig.suptitle(title, fontsize=10, color="#1f3a5f")
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    print(f"график: {out_png}")
    return out_png


def _set_base_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)


def h1(doc, text):
    p = doc.add_heading(text, level=1)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def h2(doc, text):
    p = doc.add_heading(text, level=2)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def para(doc, text, bold=False, italic=False, align=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    if align is not None:
        p.alignment = align
    return p


def bullet(doc, text):
    return doc.add_paragraph(text, style="List Bullet")


def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(htext)
        run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    return t


