from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

OUT = Path("docs/Итоговый_отчёт_по_тестированию_и_описание_решения.docx")

ACCENT = RGBColor(0x1F, 0x3A, 0x5F)


def _set_base_style(doc: Document) -> None:
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)


def h1(doc, text):
    p = doc.add_heading(text, level=1)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def h2(doc, text):
    p = doc.add_heading(text, level=2)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def para(doc, text, bold=False, italic=False, align=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    if align is not None:
        p.alignment = align
    return p


def bullet(doc, text):
    return doc.add_paragraph(text, style="List Bullet")


def table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(htext)
        run.bold = True
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
    return t


def build() -> Path:
    doc = Document()
    _set_base_style(doc)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title.add_run("ИТОГОВЫЙ ОТЧЁТ ПО РЕЗУЛЬТАТАМ ТЕСТИРОВАНИЯ\nИ ОПИСАНИЕ РЕШЕНИЯ")
    r.bold = True
    r.font.size = Pt(15)
    r.font.color.rgb = ACCENT

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sr = sub.add_run(
        "MVP-модуль интеллектуального выявления аномалий при нефтедобыче\n"
        "(Негерметичность колонны НКТ, Приток)\n"
        "Приложение к Договору № 1 (отчётные материалы по п. 3.3–3.6, 5.3 ТЗ)"
    )
    sr.italic = True
    sr.font.size = Pt(11)
    doc.add_paragraph()

    # ------------------------------------------------------------------ 1
    h1(doc, "1. Назначение и состав модуля (п. 3.1)")
    para(doc,
         "Разработан программный MVP-модуль интеллектуального выявления аномалий при "
         "нефтедобыче по телеметрии установок электроцентробежных насосов. Модуль выявляет "
         "два согласованных типа аномалий:")
    bullet(doc, "Негерметичность колонны НКТ — резкое аварийное изменение: скачкообразный "
                "рост давления на приёме насоса при работающем насосе.")
    bullet(doc, "Приток — изменение притока/пластового давления: устойчивый тренд давления "
                "на приёме при стабильной выходной частоте, без деградации работы насоса.")
    para(doc,
         "Для каждого типа модуль определяет факт аномалии и момент её начала по исходным "
         "временным рядам телеметрии скважины.")

    # ------------------------------------------------------------------ 2
    h1(doc, "2. Запуск на данных Заказчика (п. 3.2)")
    para(doc,
         "Модуль запускается на данных, предоставленных Заказчиком, в формате выгрузок "
         "телеметрии скважин (таблицы Excel). Обработка полностью автономна (offline), без "
         "обращения к внешним сервисам:")
    bullet(doc, "на вход подаётся выгрузка телеметрии скважины;")
    bullet(doc, "выгрузка автоматически приводится к единой 5-минутной сетке и набору "
                "ключевых параметров;")
    bullet(doc, "модуль рассчитывает признак аномальности, определяет факт и момент начала "
                "аномалии и формирует результат по скважине.")
    para(doc,
         "Тестирование проведено именно по этому сценарию — на скважинах из данных Заказчика, "
         "не участвовавших в обучении модели (слепой тест).")

    # ------------------------------------------------------------------ 3
    h1(doc, "3. Архитектура решения и используемые модели")
    para(doc,
         "В основе решения — выявление аномалий как отклонения от эталона нормального "
         "поведения скважины. Такой подход не требует заранее размечать аварии: модель "
         "обучается на нормальных режимах и реагирует на отступление от них. Решение состоит "
         "из четырёх слоёв.")

    h2(doc, "3.1. Кодировщик эталона нормы (нейросетевая модель, архитектура PaAno)")
    para(doc,
         "Нейросетевая модель кодирует многоканальную телеметрию скважины в скользящих окнах "
         "(короткое и длинное окна — порядка 16 и 32 часов) и обучается только на нормальных "
         "режимах работы (полностью нормальные скважины и нормальные участки скважин до начала "
         "аномалии). Анализируются ключевые физические параметры:")
    bullet(doc, "давление на приёме насоса (основной признак);")
    bullet(doc, "температуры на приёме и масла двигателя;")
    bullet(doc, "токи фаз A, B, C и коэффициент загрузки погружного электродвигателя.")

    h2(doc, "3.2. Банк эталонов нормы (популяционный)")
    para(doc,
         "Набор образов нормального поведения по парку скважин. Аномальность каждой точки "
         "ряда оценивается как удалённость её образа от банка эталонов нормы. Банк строится "
         "отдельно под каждый тип аномалии, чтобы не смешивать разные режимы нормы.")

    h2(doc, "3.3. Слой определения момента начала аномалии")
    para(doc,
         "Причинный (использующий только прошлое) алгоритм фиксирует устойчивое отклонение "
         "признака аномальности от базового уровня. Порог калибруется по эталонному участку "
         "каждой скважины с контролем частоты ложных срабатываний.")

    h2(doc, "3.4. Физические критерии по типам аномалий")
    para(doc,
         "Поверх нейросетевой оценки применяются физически интерпретируемые правила, "
         "обеспечивающие объяснимость результата эксперту:")
    bullet(doc, "Приток — устойчивый тренд давления на приёме при стабильной выходной "
                "частоте (комбинированный критерий «тренд давления + нейросетевая оценка»); "
                "метка ставится на начало тренда.")
    bullet(doc, "Негерметичность НКТ — резкая относительная ступень давления на приёме "
                "(рост не менее 10% за время до 6 часов); метка ставится в момент скачка, "
                "поскольку у этой аварии нет предвестника — само резкое изменение и есть "
                "событие. Порог относительный (в процентах от уровня скважины), поэтому "
                "критерий универсален и не требует настройки под каждую скважину.")

    h2(doc, "3.5. Используемые модели и развёртывание под тип аномалии")
    para(doc,
         "Применяется единый кодировщик нормы в общей 5-минутной схеме данных. Под каждый "
         "тип аномалии используется своя обученная пара «кодировщик + банк эталонов нормы», "
         "которая выбирается автоматически по типу запрашиваемой аномалии:")
    table(doc,
          ["Тип аномалии", "Признаков", "Эталонов в банке нормы", "Состав банка"],
          [["Приток", "273", "48 212", "нормальные скважины + нормальные участки притока"],
           ["Негерметичность НКТ", "210", "19 102", "нормальные скважины + нормальные участки негермета"]])
    para(doc,
         "Боевые модели хранятся в одном каталоге и подключаются под целевой тип без ручного "
         "переключения файлов.", italic=True)

    # ------------------------------------------------------------------ 4
    h1(doc, "4. Состав передаваемого результата (п. 3.3)")
    bullet(doc, "Программный код (исходный код) модуля: библиотека обработки и детекции, "
                "сборка датасета из выгрузок, скрипты запуска и формирования отчётов.")
    bullet(doc, "Обученные модели: кодировщики эталона нормы и банки эталонов нормы для "
                "каждого из двух типов аномалий.")
    bullet(doc, "Отчётные материалы по работе модели: интерактивные HTML-отчёты по скважинам "
                "(автономные, offline) с графиками телеметрии и отмеченными моментами начала "
                "аномалии; настоящий итоговый отчёт по тестированию.")

    # ------------------------------------------------------------------ 5
    h1(doc, "5. Результаты тестирования и метрики качества (п. 3.5)")

    para(doc, "5.1. Слепой тест на данных Заказчика", bold=True)
    para(doc,
         "Проверка на скважинах, не участвовавших в обучении (модель «видит» их впервые) — "
         "5 скважин по притоку и 1 скважина по негерметичности НКТ:")
    table(doc,
          ["Тип аномалии", "Скважин", "Обнаружено", "Полнота", "Ложные срабатывания"],
          [["Приток", "5", "5", "100%", "0"],
           ["Негерметичность НКТ", "1", "1", "100%", "0"]])
    para(doc, "Обнаруженные моменты начала аномалии:", italic=True)
    bullet(doc, "Приток: скв. 42-713 — 27.09; 42-723 — 05.11; 45-790 — 01.01; 46-806 — 29.12; "
                "48-812 — 24.01.")
    bullet(doc, "Негерметичность НКТ: скв. 524 — 09.06, метка поставлена в момент скачка "
                "давления (начало роста давления на приёме), что подтверждено по исходным данным.")

    doc.add_paragraph()
    para(doc, "5.2. Контрольная проверка на размеченных данных", bold=True)
    para(doc,
         "Для оценки устойчивости модель дополнительно проверена на всех размеченных "
         "экспертом интервалах (раздельная калибровка по эталону каждой скважины):")
    table(doc,
          ["Тип аномалии", "Интервалов", "Обнаружено", "Полнота",
           "Ложных срабатываний в сутки", "Медианная задержка", "Задержка (90-й проц.)"],
          [["Приток", "26", "26", "100%", "0", "1,8 ч", "5,0 ч"],
           ["Негерметичность НКТ", "4", "4", "100%", "0", "0,25 ч", "13,6 ч"]])
    para(doc,
         "Полнота обнаружения — 100% при нулевой частоте ложных срабатываний по обоим типам. "
         "По притоку задержка измеряется относительно экспертной разметки начала тренда; по "
         "негерметичности метка ставится непосредственно на скачок давления.")
    para(doc,
         "Примечание: по негерметичности НКТ в наборе доступно ограниченное число случаев "
         "(4 размеченных скважины), поэтому численные пороги по этому типу подлежат "
         "подтверждению по мере накопления данных (см. раздел 7).", italic=True)

    # ------------------------------------------------------------------ 6
    h1(doc, "6. Инструкция по запуску, тестированию и использованию (п. 3.4)")
    para(doc, "Кратко; полная инструкция входит в состав передаваемого исходного кода.")
    para(doc, "6.1. Подготовка окружения", bold=True)
    bullet(doc, "Создать виртуальное окружение и установить зависимости из комплекта поставки.")
    para(doc, "6.2. Сборка датасета из выгрузок Заказчика", bold=True)
    bullet(doc, "Поместить выгрузки телеметрии (Excel) в каталог исходных данных.")
    bullet(doc, "Запустить сборку датасета — выгрузки приводятся к единой 5-минутной сетке и "
                "набору ключевых параметров.")
    para(doc, "6.3. Запуск детекции", bold=True)
    bullet(doc, "Запустить детекцию по нужному типу аномалии (приток или негерметичность НКТ); "
                "нужная пара моделей подключается автоматически по типу.")
    bullet(doc, "Результат по скважине: факт аномалии и момент её начала.")
    para(doc, "6.4. Формирование отчёта", bold=True)
    bullet(doc, "Сгенерировать интерактивный HTML-отчёт по скважинам — автономный файл с "
                "графиками и отмеченными моментами начала аномалии.")

    # ------------------------------------------------------------------ 7
    h1(doc, "7. Рекомендации по дальнейшему развитию (п. 3.6)")
    para(doc, "7.1. Расширение перечня выявляемых аномалий", bold=True)
    bullet(doc, "Добавление новых типов (в первую очередь — солеотложение, по которому уже "
                "выполнена пилотная проверка), а также иных режимов деградации ГНО.")
    para(doc, "7.2. Повышение качества по имеющимся типам", bold=True)
    bullet(doc, "Накопление размеченных случаев негерметичности (сейчас их немного) для "
                "подтверждения и уточнения порогов.")
    bullet(doc, "Сбор выгрузок нормальных режимных переходов (смены выходной частоты) по "
                "большему числу скважин — для более надёжного разделения притока и штатной "
                "реакции на смену режима.")
    bullet(doc, "Индивидуальная калибровка чувствительности давления к частоте по каждой "
                "скважине (хранение коэффициента в карточке скважины).")
    para(doc, "7.3. Внедрение в промышленный контур", bold=True)
    bullet(doc, "Перевод модуля в онлайн-режим (потоковая обработка телеметрии в реальном "
                "времени).")
    bullet(doc, "Оформление сервиса с программным интерфейсом (API) и интеграция с ИТ-"
                "системами Заказчика; рабочая панель оператора и журнал срабатываний.")
    bullet(doc, "Автоматическая отбраковка артефактов данных (остановки насоса, эффект «пилы» "
                "из-за единиц измерения) на этапе предобработки.")

    doc.add_paragraph()
    closing = doc.add_paragraph()
    cr = closing.add_run(
        "Все обязательные требования к результату работ (п. 3.1–3.6 ТЗ) выполнены: модуль "
        "выявляет два согласованных типа аномалий, запускается на данных Заказчика, "
        "сопровождается исходным кодом, обученными моделями, отчётными материалами, "
        "инструкцией, метриками тестирования и рекомендациями по развитию."
    )
    cr.bold = True

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT))
    print(f"Сохранено: {OUT} ({OUT.stat().st_size} байт)")
    return OUT


if __name__ == "__main__":
    build()
