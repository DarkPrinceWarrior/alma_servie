# ----------------------------------------------------------------------- графики
def _col(df, *needles):
    for c in df.columns:
        cl = str(c).lower().replace("ё", "е")
        if all(n in cl for n in needles):
            return c
    return None


def _plot_well(src_dir: str, title: str, out_png: Path, onset_override: str | None = None) -> Path | None:
    src = Path(src_dir) / "source.parquet"
    starts = Path(src_dir) / "predicted_starts.parquet"
    if not src.exists():
        print(f"[график пропущен] нет {src}")
        return None
    df = pd.read_parquet(src)
    df["timestamp"] = pd.to_datetime(df["timestamp"])
    df = df.sort_values("timestamp")
    p = _col(df, "давление", "прием")
    f = _col(df, "выходная", "частота")
    onset = None
    if onset_override is not None:
        onset = pd.to_datetime(onset_override)
    elif starts.exists():
        st = pd.read_parquet(starts)
        if len(st) and "detected_time" in st.columns:
            onset = pd.to_datetime(st["detected_time"]).min()

    fig, axes = plt.subplots(2, 1, figsize=(9.2, 5.0), sharex=True, gridspec_kw={"height_ratios": [2, 1]})
    ax0, ax1 = axes
    ax0.plot(df["timestamp"], df[p], color="#1a1a1a", linewidth=1.1, label="Давление на приёме, кгс/см²")
    ax0.set_ylabel("Давление, кгс/см²")
    ax0.grid(True, alpha=0.25)
    ax0.legend(loc="upper left", fontsize=8)
    if f is not None:
        ax1.plot(df["timestamp"], df[f], color="#555555", linewidth=1.0, label="Выходная частота, Гц")
        ax1.set_ylabel("Частота, Гц")
        ax1.grid(True, alpha=0.25)
        ax1.legend(loc="upper left", fontsize=8)
    if onset is not None:
        for ax in axes:
            ax.axvline(onset, color="#b00000", linestyle="--", linewidth=1.4)
        ax0.text(onset, ax0.get_ylim()[1], " момент начала аномалии",
                 color="#b00000", fontsize=8, va="top", ha="left")
    ax1.xaxis.set_major_formatter(mdates.DateFormatter("%d.%m"))
    fig.suptitle(title, fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=130)
    plt.close(fig)
    print(f"график: {out_png}")
    return out_png


# ----------------------------------------------------------------------- стили
def _set_base_style(doc: Document) -> None:
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    st.paragraph_format.space_after = Pt(6)
    st.paragraph_format.line_spacing = 1.15


def _black_heading(p):
    # строгое оформление: чёрные заголовки Times New Roman, без цветовой разметки
    for run in p.runs:
        run.font.name = "Times New Roman"
        run.font.color.rgb = RGBColor(0, 0, 0)
    return p


def h1(doc, text):
    p = doc.add_heading(text, level=1)
    return _black_heading(p)


def h2(doc, text):
    p = doc.add_heading(text, level=2)
    return _black_heading(p)


def para(doc, text, bold=False, italic=False, align="justify", size=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY if align == "justify" else (
        WD_ALIGN_PARAGRAPH.CENTER if align == "center" else WD_ALIGN_PARAGRAPH.LEFT)
    return p


def bullet(doc, text):
    return doc.add_paragraph(text, style="List Bullet")


def numbered(doc, text):
    return doc.add_paragraph(text, style="List Number")


def code_block(doc, lines):
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), "F2F2F2")
    pPr.append(shd)
    p.paragraph_format.left_indent = Pt(6)
    run = p.add_run("\n".join(lines))
    run.font.name = "Courier New"
    run.font.size = Pt(9)
    return p


def table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(htext)
        run.bold = True
        run.font.size = Pt(10)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val))
            r.font.size = Pt(10)
    return t


def caption(doc, text):
    c = doc.add_paragraph()
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = c.add_run(text)
    r.italic = True
    r.font.size = Pt(9)
    return c


